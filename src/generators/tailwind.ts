import type { ThemeTokens } from '../types.js';
import { buildPalette, darken, lighten, readableOn, withAlpha, ensureContrast } from '../color.js';

/**
 * Tailwind CSS v4 `@theme` block.
 *
 * Uses `@theme inline` + CSS custom properties so themes can be swapped at
 * runtime without a rebuild, and every derived value (hover, muted text,
 * borders, ramps) is computed in LCH instead of channel arithmetic.
 */
export function generateTailwindConfig(tokens: ThemeTokens): string {
  const { primary, secondary, accent, surface, text } = tokens;
  const textBody = ensureContrast(withAlpha(text, 0.85), surface, 4.5);
  const ramp = buildPalette(primary).ramp;

  return `/* Generated by theme-bridge — Tailwind CSS v4 theme block. Do not edit by hand. */

@import "tailwindcss";

@theme inline {
  /* ── Brand ── */
  --color-brand-primary: ${primary};
  --color-brand-primary-hover: ${lighten(primary, 6)};
  --color-brand-primary-active: ${darken(primary, 6)};
  --color-brand-primary-fg: ${readableOn(primary).color};
  --color-brand-secondary: ${secondary};
  --color-brand-secondary-fg: ${readableOn(secondary).color};
  --color-brand-accent: ${accent};
  --color-brand-accent-fg: ${readableOn(accent).color};

  /* ── Neutral ── */
  --color-surface: ${surface};
  --color-text-primary: ${text};
  --color-text-body: ${textBody.color};
  --color-text-muted: ${withAlpha(text, 0.55)};
  --color-border-light: ${withAlpha(text, 0.1)};
  --color-border-default: ${withAlpha(text, 0.2)};

  /* ── Primary ramp (50-900) ── */
${Object.entries(ramp)
  .map(([step, value]) => `  --color-primary-${step}: ${value};`)
  .join('\n')}

  /* ── Accent states ── */
  --color-accent-bg: ${withAlpha(accent, 0.12)};
  --color-accent-text: ${darken(accent, 10)};
  --color-accent-border: ${withAlpha(accent, 0.3)};
}
`;
}
