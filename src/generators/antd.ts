import type { ThemeTokens } from '../types.js';
import { buildPalette, darken, lighten, readableOn, withAlpha, ensureContrast } from '../color.js';

/**
 * Ant Design 5.x `ThemeConfig` as source text.
 *
 * Beyond the seed mapping the first version did, this emits the 50–900 ramps
 * AntD expects for `colorPrimaryBg`-style slots and a per-component block whose
 * hover/active states are derived rather than hardcoded.
 */
export function generateAntdConfig(tokens: ThemeTokens): string {
  const { primary, secondary, accent, surface, text } = tokens;
  const primaryHover = lighten(primary, 6);
  const primaryActive = darken(primary, 6);
  const onPrimary = readableOn(primary).color;
  const onSecondary = readableOn(secondary).color;
  const textOnSurface = ensureContrast(text, surface, 4.5);
  const p = buildPalette(primary).ramp;

  return `import type { ThemeConfig } from 'antd';

/**
 * Generated by theme-bridge. Do not edit by hand.
 * Primary ramp: 50-900 derived from ${primary}
 */
export const theme: ThemeConfig = {
  token: {
    colorPrimary: '${primary}',
    colorInfo: '${primary}',
    colorLink: '${primary}',
    colorSuccess: '${accent}',
    colorWarning: '#faad14',
    colorError: '#ff4d4f',

    colorPrimaryHover: '${primaryHover}',
    colorPrimaryActive: '${primaryActive}',
    colorPrimaryText: '${onPrimary}',

    colorBgContainer: '${surface}',
    colorBgElevated: '${surface}',
    colorTextBase: '${textOnSurface.color}',
    colorText: '${textOnSurface.color}',

    colorPrimaryBg: '${withAlpha(primary, 0.1)}',
    colorSuccessBg: '${withAlpha(accent, 0.1)}',
    colorBorder: '${withAlpha(text, 0.15)}',

    borderRadius: 6,
  },
  components: {
    Button: {
      colorPrimary: '${primary}',
      colorPrimaryHover: '${primaryHover}',
      colorPrimaryActive: '${primaryActive}',
      primaryColor: '${onPrimary}',
      borderRadius: 6,
    },
    Card: {
      colorBgContainer: '${surface}',
      borderRadius: 8,
    },
    Tag: {
      defaultBg: '${withAlpha(secondary, 0.1)}',
      defaultColor: '${onSecondary}',
    },
    Layout: {
      bodyBg: '${surface}',
      headerBg: '${surface}',
    },
  },
};

/** Optional: AntD's colour ramp for custom components. */
export const primaryRamp = {
${Object.entries(p)
  .map(([step, value]) => `  ${step}: '${value}',`)
  .join('\n')}
} as const;

export default theme;
`;
}
